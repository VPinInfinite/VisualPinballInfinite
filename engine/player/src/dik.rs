/// The DirectInput key code of an SDL scancode, as VPX converts it.
pub fn from_scancode(scancode: u32) -> u8 {
    SDL_SCANCODE_TO_DIK.get(scancode as usize).copied().unwrap_or(0)
}

/// VPX's default key assignments, as DirectInput codes.
pub mod default_keys {
    pub const LEFT_FLIPPER: u8 = 0x2A; // left Shift
    pub const RIGHT_FLIPPER: u8 = 0x36; // right Shift
    pub const STAGED_LEFT_FLIPPER: u8 = 0xDB; // left Windows key
    pub const STAGED_RIGHT_FLIPPER: u8 = 0xB8; // right Alt
    pub const LEFT_TILT: u8 = 0x2C; // Z
    pub const RIGHT_TILT: u8 = 0x35; // slash
    pub const CENTER_TILT: u8 = 0x39; // space
    pub const PLUNGER: u8 = 0x1C; // Enter
    pub const ADD_CREDIT: u8 = 0x06; // 5
    pub const ADD_CREDIT_2: u8 = 0x05; // 4
    pub const START_GAME: u8 = 0x02; // 1
    pub const MECH_TILT: u8 = 0x14; // T
    pub const RIGHT_MAGNA_SAVE: u8 = 0x9D; // right Ctrl
    pub const LEFT_MAGNA_SAVE: u8 = 0x1D; // left Ctrl
    pub const EXIT_GAME: u8 = 0x10; // Q
    pub const LOCKBAR: u8 = 0x38; // left Alt
    pub const ESCAPE: u8 = 0x01;
    pub const PAUSE: u8 = 0x19; // P
}

/// The keys a table's script knows by name (`LeftFlipperKey`...), handed
/// over as DirectInput codes, VPX's defaults until our settings screen
/// exists. (Build 5436 hands scripts action numbers instead; to settle with
/// the input work.)
#[derive(Clone, Copy, Debug)]
pub struct Keys {
    pub left_flipper: u8,
    pub right_flipper: u8,
    pub staged_left_flipper: u8,
    pub staged_right_flipper: u8,
    pub left_tilt: u8,
    pub right_tilt: u8,
    pub center_tilt: u8,
    pub plunger: u8,
    pub add_credit: u8,
    pub add_credit_2: u8,
    pub start_game: u8,
    pub mech_tilt: u8,
    pub right_magna_save: u8,
    pub left_magna_save: u8,
    pub exit_game: u8,
    pub lockbar: u8,
}

impl Default for Keys {
    fn default() -> Self {
        use default_keys::*;
        Keys {
            left_flipper: LEFT_FLIPPER,
            right_flipper: RIGHT_FLIPPER,
            staged_left_flipper: STAGED_LEFT_FLIPPER,
            staged_right_flipper: STAGED_RIGHT_FLIPPER,
            left_tilt: LEFT_TILT,
            right_tilt: RIGHT_TILT,
            center_tilt: CENTER_TILT,
            plunger: PLUNGER,
            add_credit: ADD_CREDIT,
            add_credit_2: ADD_CREDIT_2,
            start_game: START_GAME,
            mech_tilt: MECH_TILT,
            right_magna_save: RIGHT_MAGNA_SAVE,
            left_magna_save: LEFT_MAGNA_SAVE,
            exit_game: EXIT_GAME,
            lockbar: LOCKBAR,
        }
    }
}
